const avatar = computed(() => {
  return userStore.userInfo?.avatar ?? preferences.app.defaultAvatar;
});

async function handleLogout() {
  await authStore.logout(false);
}

// ===== 座席端 WS Channel 生命周期（绑定登录态） =====
// Channel 在 accessToken 存在时建连，token 刷新时换 token 重建，登出时销毁。
// 设计文档：docs/superpowers/specs/2026-07-09-agent-ws-single-channel-design.md
const agentChannel = useAgentWsChannel();

watch(
  () => accessStore.accessToken,
  (newToken, oldToken) => {
    if (newToken && !oldToken) {
      // 首次登录：全量初始化
      agentChannel.init(newToken, {
        onKickedOut: () => {
          antMessage.warning('您的账号已在其他设备登录，当前连接已断开');
        },
      });
    } else if (newToken && newToken !== oldToken) {
      // token 刷新：保留 subscriberMap，只换 token 重建 WS
      agentChannel.reconnect(newToken);
    } else if (!newToken) {
      // 登出：销毁 channel
      agentChannel.dispose();
    }
  },
  { immediate: true },
);

// 401 握手失败耗尽重试后 status='error'。
// token 刷新由 HTTP 拦截器处理；此处仅在 WS 连接彻底失败时提示用户刷新页面。
watch(
  () => agentChannel.status.value,
  (s) => {
    if (s === 'error') {
      antMessage.warning('与服务器的连接已断开，请刷新页面重试');
    }
  },
);

// ===== 座席端 SSE Queue Channel 生命周期（绑定登录态） =====
// 随 WS Channel 同步建连/销毁，保证离开 agent 页面后队列推送不中断。
const queueChannel = useSessionQueueChannel();

watch(
  () => accessStore.accessToken,
  async (newToken, oldToken) => {
    if (newToken && !oldToken) {
      // 首次登录：建立 SSE 连接 + 加载初始队列
      queueChannel.init();
      await queueChannel.loadSessions();
    } else if (newToken && newToken !== oldToken) {
      // token 刷新：重建 SSE 连接以使用新 token
      queueChannel.reconnect();
    } else if (!newToken) {
      // 登出：销毁 SSE channel
      queueChannel.dispose();
    }
  },
  { immediate: true },
);

function handleNoticeClear() {
  notifications.value = [];
}

function markRead(id: number | string) {
  const item = notifications.value.find((item) => item.id === id);
  if (item) {
    item.isRead = true;
  }
}

function remove(id: number | string) {
  notifications.value = notifications.value.filter((item) => item.id !== id);
}

function handleMakeAll() {
  notifications.value.forEach((item) => (item.isRead = true));
}

const viewAll = () => {};

const handleClick = (item: NotificationItem) => {
  // 如果通知项有链接，点击时跳转
  if (item.link) {
    navigateTo(item.link, item.query, item.state);
  }
};

function navigateTo(
  link: string,
  query?: Record<string, any>,
  state?: Record<string, any>,
) {
  if (link.startsWith('http://') || link.startsWith('https://')) {
    // 外部链接，在新标签页打开
    window.open(link, '_blank');
  } else {
    // 内部路由链接，支持 query 参数和 state
    router.push({
      path: link,
      query: query || {},
      state,
    });
  }
}

watch(
  () => ({
    enable: preferences.app.watermark,
    content: preferences.app.watermarkContent,
    isDark: isDark.value,
  }),
  async ({ enable, content, isDark: isDarkValue }) => {
    if (enable) {
      const watermarkColor = isDarkValue
        ? 'rgba(255, 255, 255, 0.12)'
        : 'rgba(0, 0, 0, 0.12)';

      await updateWatermark({
        advancedStyle: {
          colorStops: [
            {
              color: watermarkColor,
              offset: 0,
            },
            {
              color: watermarkColor,
              offset: 1,
            },
          ],
          type: 'linear',
        },
        content:
          content ||
          `${userStore.userInfo?.username} - ${userStore.userInfo?.realName}`,
      });
    } else {
      destroyWatermark();
    }
  },
  {
    immediate: true,
  },
);
</script>

